#ifndef DRV_PWM_H
#define DRV_PWM_H

#include "main.h"

typedef struct {
    TIM_HandleTypeDef *htim;     // який таймер (&htim3)
    uint32_t           channel;  // який канал (TIM_CHANNEL_1 → пін PA6)
} Pwm_t;

void Pwm_Init   (Pwm_t *p, TIM_HandleTypeDef *htim, uint32_t channel);  // стартує з 0 %
void Pwm_SetDuty(Pwm_t *p, float duty01);                               // 0.0 … 1.0

#endif /* DRV_PWM_H */
