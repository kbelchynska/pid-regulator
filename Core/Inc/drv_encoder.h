/* ============================================================================
 * drv_encoder.h — ДРАЙВЕР ЕНКОДЕРА KY-040 на апаратному таймері TIM4
 * ============================================================================
 * НАВІЩО: перетворити лічильник таймера на зрозуміле "скільки клацань і в
 *         який бік з минулого разу".
 *
 * ЯК ПРАЦЮЄ:
 *   Таймер сам рахує імпульси A/B без переривань і без втрат. Драйвер раз на
 *   10 мс читає лічильник, рахує різницю з минулим разом і переводить
 *   імпульси в клацання (4 імпульси = 1 клацання). Неповні клацання
 *   зберігає на потім.
 *
 * ЧОМУ АПАРАТНИЙ ТАЙМЕР, а не переривання на пінах: таймер рахує КОЖЕН
 * імпульс, навіть якщо процесор зайнятий. Переривання на кожен фронт при
 * швидкому крученні завантажували б процесор і могли губити кроки.
 * ========================================================================== */
#ifndef DRV_ENCODER_H
#define DRV_ENCODER_H

#include "main.h"
#include <stdbool.h>
#include <stdint.h>

typedef struct {
    TIM_HandleTypeDef *htim;         // який таймер (у нас &htim4)
    uint16_t last_cnt;               // значення лічильника при минулому читанні
    int32_t  remainder;              // імпульси, що ще не склали повне клацання
    int32_t  counts_per_detent;      // скільки імпульсів = 1 клацання (4)
    bool     invert;                 // поміняти напрямок
} Encoder_t;

void    Encoder_Init(Encoder_t *e, TIM_HandleTypeDef *htim,
                     int32_t counts_per_detent, bool invert);

/* > 0 — стільки клацань за годинниковою з минулого виклику, < 0 — проти, 0 — не крутили */
int32_t Encoder_ReadDetents(Encoder_t *e);

#endif /* DRV_ENCODER_H */
