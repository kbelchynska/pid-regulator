/* ============================================================================
 * svc_event_bus.h — ШИНА ПОДІЙ (патерн Observer / Publish–Subscribe)
 * ============================================================================
 * НАВІЩО: щоб модулі спілкувалися, НЕ ЗНАЮЧИ один про одного.
 *   Задача вводу повідомляє "енкодер клацнув +1" — і це отримують ОДРАЗУ два
 *   модулі: мотор і PID. Сама задача вводу про них не знає.
 *
 * ЯК ПРАЦЮЄ: модулі при старті ПІДПИСУЮТЬСЯ на теми (передають свою
 *   функцію-обробник). Коли хтось ПУБЛІКУЄ подію на тему — шина по черзі
 *   викликає всіх підписників. Додати новий "слухач" (дисплей, лог) =
 *   один рядок Subscribe; код видавця не змінюється.
 *
 * ДВА ВАЖЛИВІ ОБМЕЖЕННЯ (для RTOS):
 *   1) підписка — ЛИШЕ до старту планувальника. Тоді масив під час роботи
 *      не змінюється і захищати його м'ютексом не треба;
 *   2) функція-підписник виконується В ЗАДАЧІ ТОГО, ХТО ПУБЛІКУЄ — тому
 *      має бути короткою і нічого не чекати (лише покласти в чергу / пін).
 * ========================================================================== */
#ifndef SVC_EVENT_BUS_H
#define SVC_EVENT_BUS_H

#include <stdbool.h>
#include <stdint.h>

typedef enum {                 // ТЕМИ ("канали"), на які можна підписатися
    TOPIC_ENCODER_STEP = 0,    // клацання енкодера; value = +N (за годинниковою) / −N (проти)
    TOPIC_BUTTON,              // натиснули кнопку; value = 1
    TOPIC_MOTOR_STATE,         // змінився стан мотора; value = MotorState_t
    TOPIC_REG_SETTLED,         // PID вийшов на уставку (1) / ще йде до неї (0)
    TOPIC_COUNT                // прийом: останній елемент = кількість тем (4)
} BusTopic_t;

typedef void (*BusCallback_t)(void *ctx, BusTopic_t topic, int32_t value);
// ↑ тип "функції-слухача": шина викличе її з темою і значенням.
//   ctx — довільний контекст, який підписник передав при підписці

#define EVENT_BUS_MAX_SUBSCRIBERS  8          // максимум підписників

bool EventBus_Subscribe(BusTopic_t topic, BusCallback_t cb, void *ctx);  // підписатися
void EventBus_Publish  (BusTopic_t topic, int32_t value);               // опублікувати

#endif /* SVC_EVENT_BUS_H */
