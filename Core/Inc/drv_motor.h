/* ============================================================================
 * drv_motor.h — АБСТРАКТНИЙ ІНТЕРФЕЙС МОТОРА ("що вміє мотор", без "як")
 * ============================================================================
 * НАВІЩО:
 *   Описує, ЩО вміє будь-який мотор (крутитись у заданий бік і зупинятись),
 *   але не ЯК. Логіка керування працює ЛИШЕ з цим інтерфейсом і не знає, що
 *   всередині два реле. Завтра поставите драйвер MX1616 — напишете нову
 *   реалізацію з тими ж двома функціями, а логіка не зміниться.
 *
 * ЯК ПРАЦЮЄ:
 *   На C немає класів, тому "віртуальні методи" робимо через ТАБЛИЦЮ
 *   ВКАЗІВНИКІВ НА ФУНКЦІЇ (vtable) — так само, як це робить компілятор C++.
 *
 * ПАТЕРНИ І ПРИНЦИПИ:
 *   Strategy / Interface;
 *   Open/Closed — систему можна розширювати новими моторами, не змінюючи код;
 *   Dependency Inversion — логіка залежить від абстракції, а не від реле.
 * ========================================================================== */
#ifndef DRV_MOTOR_H
#define DRV_MOTOR_H

typedef enum {                 // перелік: іменовані константи замість "магічних" 0 і 1
    MOTOR_DIR_CW = 0,          // за годинниковою стрілкою
    MOTOR_DIR_CCW              // проти годинникової (автоматично = 1)
} MotorDir_t;

typedef struct {                                   // ТАБЛИЦЯ ОПЕРАЦІЙ (vtable)
    void (*run) (void *self, MotorDir_t dir);      // вказівник на функцію "крутити":
                                                   // змінна run зберігає АДРЕСУ функції
    void (*stop)(void *self);                      // вказівник на функцію "стоп"
} MotorOps_t;

typedef struct {                                   // АБСТРАКТНИЙ МОТОР
    const MotorOps_t *ops;     // які функції викликати (таблиця конкретної реалізації)
    void             *self;    // дані конкретної реалізації; void* = "вказівник на будь-що"
} Motor_t;

/* Зручні обгортки: взяти з таблиці адресу функції і викликати її, передавши дані
   реалізації. static inline — компілятор вставить тіло на місце виклику.       */
static inline void Motor_Run (const Motor_t *m, MotorDir_t dir) { m->ops->run(m->self, dir); }
static inline void Motor_Stop(const Motor_t *m)                 { m->ops->stop(m->self); }

#endif /* DRV_MOTOR_H */
