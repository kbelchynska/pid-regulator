/* ============================================================================
 * app_motor_ctrl.h — ЗАДАЧА МОТОРА (патерн Active Object)
 * ============================================================================
 * НАВІЩО: "оживити" автомат станів. Створюється окрема задача FreeRTOS з
 *   власною чергою подій. Вона отримує події від енкодера й кнопки,
 *   передає автомату і щотакту подає MEV_TICK.
 *
 * ACTIVE OBJECT = власна задача + власна черга + приватний стан.
 *   Модуль сам підписується на шину (TOPIC_ENCODER_STEP, TOPIC_BUTTON) і
 *   кладе отримані події у свою чергу. Реле керує ЛИШЕ ця одна задача →
 *     - немає гонок даних;
 *     - не потрібні м'ютекси → неможливий deadlock та інверсія пріоритетів.
 * ========================================================================== */
#ifndef APP_MOTOR_CTRL_H
#define APP_MOTOR_CTRL_H

#include "app_motor_fsm.h"
#include <stdbool.h>

void         MotorCtrl_Init(Motor_t motor);      // створити чергу і задачу (до старту ОС)
bool         MotorCtrl_Post(MotorEvent_t ev);    // покласти подію в чергу (з будь-якої задачі, не блокує)
MotorState_t MotorCtrl_GetState(void);           // поточний стан (для діагностики)
uint32_t     MotorCtrl_DroppedEvents(void);      // скільки подій загубилось (черга була повна)

#endif /* APP_MOTOR_CTRL_H */
