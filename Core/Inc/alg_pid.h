/* ============================================================================
 * alg_pid.h — PID-РЕГУЛЯТОР (шар "алгоритми": чиста математика)
 * ============================================================================
 * НАВІЩО: за похибкою "уставка − вимір" обчислити керування (ШІМ), щоб
 *   вихід став рівним уставці.
 *
 * ОСОБЛИВІСТЬ: жодних main.h / HAL / FreeRTOS — модуль незалежний від заліза,
 *   тому перевіряється тестами на звичайному ПК (tests/test_pid.c).
 *
 * ТЕОРІЯ:
 *   u(t) = Kp·e(t) + Ki·∫e(t)dt + Kd·de(t)/dt,     e = уставка − вимір
 *     P — дивиться на похибку ЗАРАЗ: що більша похибка, то сильніше тиснемо;
 *     I — на суму похибок У МИНУЛОМУ: прибирає статичну похибку;
 *     D — на швидкість зміни ("МАЙБУТНЄ"): гальмує, менше перелітання.
 *   Мікроконтролер рахує ДИСКРЕТНО, раз на Ts = 0,01 с: інтеграл → сума,
 *   похідна → різниця.
 *
 * ПРАКТИЧНІ ДОПОВНЕННЯ ДО "ШКІЛЬНОЇ" ФОРМУЛИ:
 *   - D рахується по ВИМІРЮВАННЮ, а не по похибці → немає "удару" (derivative
 *     kick), коли енкодером різко змінюють уставку;
 *   - D пропущена через ФНЧ 1-го порядку → не підсилює шум АЦП;
 *   - anti-windup: умовне інтегрування + обмеження інтегратора → після
 *     насичення ШІМ вихід не перелітає уставку;
 *   - інтегратор зберігає вже помножене Ki·∫e → зміна Ki на льоту без стрибка.
 * ========================================================================== */
#ifndef ALG_PID_H
#define ALG_PID_H

#include <stdbool.h>

typedef struct {
    /* ПАРАМЕТРИ */
    float kp, ki, kd;         // коефіцієнти P, I, D
    float ts;                 // період дискретизації, с (0,01)
    float tau;                // стала часу фільтра D-складової, с (0,02; має бути ≥ 2·ts)
    float out_min, out_max;   // межі виходу (0 … 1 = 0 … 100 % ШІМ)

    /* СТАН ("пам'ять" регулятора між викликами) */
    float integ;              // накопичена I-складова (вже помножена на Ki)
    float diff;               // відфільтрована D-складова
    float prev_meas;          // вимірювання на попередньому кроці (для похідної)
    bool  first;              // це перший виклик?

    /* ДІАГНОСТИКА — складові останнього кроку (видно в дебагері) */
    float p_term, i_term, d_term;
} PID_Controller_t;

void  PID_Init(PID_Controller_t *pid, float kp, float ki, float kd,
               float ts, float tau, float out_min, float out_max);        // створити
void  PID_SetGains(PID_Controller_t *pid, float kp, float ki, float kd);  // змінити коефіцієнти
void  PID_Reset(PID_Controller_t *pid);                                   // стерти пам'ять
float PID_Update(PID_Controller_t *pid, float setpoint, float measurement); // ОДИН КРОК → 0…1

#endif /* ALG_PID_H */
