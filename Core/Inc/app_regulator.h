/* ============================================================================
 * app_regulator.h — ЗАДАЧА PID-РЕГУЛЯТОРА НАПРУГИ НА RC-КОЛІ (Active Object)
 * ============================================================================
 * НАВІЩО: кожні РІВНО 10 мс замикати контур: виміряти → порахувати PID →
 *   оновити ШІМ. Плюс — приймати нові уставки від енкодера і віддавати
 *   телеметрію в дебагер.
 *
 *   уставка ──►(−)──► PID ──► ШІМ (PA6) ──► RC-коло ──┬──► напруга
 *   (енкодер)   ▲                                     │
 *               └──────── АЦП (PA1) ◄─────────────────┘
 *
 *   - енкодер за годинниковою → уставка +100 мВ, проти → −100 мВ;
 *   - кнопка енкодера → уставка 0 В (безпечний стан);
 *   - коли вихід тримається біля уставки → публікує TOPIC_REG_SETTLED.
 *
 * НАЛАШТУВАННЯ "НА ЖИВО" (без UART):
 *   g_reg        — поточні значення (дивитися в Live Expressions);
 *   g_pid_tuning — коефіцієнти; змінити в дебагері або STM32CubeMonitor —
 *                  регулятор підхопить їх на наступному такті.
 * ========================================================================== */
#ifndef APP_REGULATOR_H
#define APP_REGULATOR_H

#include "drv_pwm.h"
#include "drv_adc.h"
#include <stdbool.h>
#include <stdint.h>

typedef struct {               // ТЕЛЕМЕТРІЯ
    int32_t  setpoint_mv;      // уставка, мВ
    int32_t  measured_mv;      // виміряна напруга на PA1, мВ
    int32_t  error_mv;         // уставка − вимір
    float    duty_pct;         // ШІМ, %
    float    p, i, d;          // складові PID (частки 0…1)
    bool     settled;          // вийшов на уставку
    uint32_t exec_us;          // скільки мкс зайняв останній такт
    uint32_t exec_us_max;      // найдовший такт
    uint32_t overruns;         // скільки разів не встиг у свій період 10 мс
} RegStatus_t;

typedef struct {
    float kp, ki, kd;          // коефіцієнти, які можна змінити в дебагері
} PidTuning_t;

extern volatile RegStatus_t g_reg;         // extern: "змінна існує, визначена в .c-файлі"
extern volatile PidTuning_t g_pid_tuning;  // лише читати / можна змінювати в дебагері

void Regulator_Init(Pwm_t *pwm, AdcIn_t *adc);   // отримує вихід і вхід ззовні; до старту ОС

#endif /* APP_REGULATOR_H */
