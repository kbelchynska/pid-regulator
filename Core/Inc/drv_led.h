/* ============================================================================
 * drv_led.h — ДРАЙВЕР СВІТЛОДІОДА
 * ============================================================================
 * Шар: драйвери. Знає лише про DigitalOut_t (BSP), не про HAL.
 *
 * НАВІЩО: об'єкт "світлодіод" уміє вмикатися, вимикатися і перемикатися
 * (Toggle). Щоб уміти Toggle — пам'ятає свій стан.
 *
 * "ОБ'ЄКТ" НА C: структура Led_t — дані об'єкта; функції з першим параметром
 * Led_t *led — його методи. led->on у C — те саме, що this->on у C++.
 * ========================================================================== */
#ifndef DRV_LED_H
#define DRV_LED_H

#include "bsp_gpio.h"          // використовує шар BSP

typedef struct {
    DigitalOut_t out;          // на якому піні і з якою полярністю
    bool         on;           // поточний стан (щоб уміти Toggle)
} Led_t;

void Led_Init  (Led_t *led, DigitalOut_t out);   // створити (вимкнений)
void Led_Set   (Led_t *led, bool on);            // увімкнути / вимкнути
void Led_Toggle(Led_t *led);                     // перемкнути

#endif /* DRV_LED_H */
