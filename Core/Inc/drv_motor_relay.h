/* ============================================================================
 * drv_motor_relay.h — МОТОР НА ДВОХ РЕЛЕ (реалізація інтерфейсу Motor_t)
 * ============================================================================
 * НАВІЩО: конкретна реалізація абстрактного мотора для нашої схеми
 *         ("H-міст на реле": COM1/COM2 — дроти мотора, NO — +5 В, NC — GND).
 *
 * ЯК ПРАЦЮЄ:
 *   за годинниковою — реле 1 увімкнене, реле 2 вимкнене;
 *   проти            — навпаки;
 *   стоп             — обидва вимкнені (обидва дроти на GND → мотор гальмує).
 * ========================================================================== */
#ifndef DRV_MOTOR_RELAY_H
#define DRV_MOTOR_RELAY_H

#include "drv_motor.h"        // інтерфейс, який реалізуємо
#include "drv_relay.h"        // реле, з яких складається

typedef struct {
    Relay_t *relay_cw;        // реле 1: увімкнене → мотор за годинниковою
    Relay_t *relay_ccw;       // реле 2: увімкнене → мотор проти
} MotorRelay_t;

void    MotorRelay_Init(MotorRelay_t *m, Relay_t *relay_cw, Relay_t *relay_ccw);
Motor_t MotorRelay_AsMotor(MotorRelay_t *m);   // "запакувати" в абстрактний Motor_t

#endif /* DRV_MOTOR_RELAY_H */
