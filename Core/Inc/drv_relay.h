/* ============================================================================
 * drv_relay.h — ДРАЙВЕР МОДУЛЯ РЕЛЕ SRD-05VDC
 * ============================================================================
 * Шар: драйвери.
 *
 * НАВІЩО: об'єкт "реле". Будова як у світлодіода, але це ІНШИЙ пристрій з
 * іншим змістом. Окремий тип робить код читабельним: у логіці видно
 * Relay_Set, а не "світлодіод, який насправді реле".
 *
 * Полярність (Low/High trigger) задається описом піна DigitalOut_t — сам
 * драйвер оперує лише "увімкнено/вимкнено".
 * ========================================================================== */
#ifndef DRV_RELAY_H
#define DRV_RELAY_H

#include "bsp_gpio.h"

typedef struct {
    DigitalOut_t out;     // пін реле (для Low-trigger: active_low=true, open_drain=true)
    bool         on;      // поточний стан
} Relay_t;

void Relay_Init (Relay_t *r, DigitalOut_t out);   // після Init реле гарантовано вимкнене
void Relay_Set  (Relay_t *r, bool on);            // увімкнути / вимкнути
bool Relay_IsOn (const Relay_t *r);               // дізнатися стан

#endif /* DRV_RELAY_H */
