/* ============================================================================
 * drv_adc.h — ДРАЙВЕР АЦП (вхід регулятора, "очі")
 * ============================================================================
 * НАВІЩО: виміряти напругу на PA1 у мілівольтах.
 *
 * ЯК ПРАЦЮЄ: 8 вимірювань поспіль (oversampling) → середнє → мВ.
 *   Усереднення N вимірювань зменшує випадковий шум у √N разів (√8 ≈ 2,8).
 *   Ціна: 8 × 4,6 мкс ≈ 40 мкс раз на 10 мс — менше 0,5 % часу процесора.
 * ========================================================================== */
#ifndef DRV_ADC_H
#define DRV_ADC_H

#include "main.h"
#include <stdint.h>

typedef struct {
    ADC_HandleTypeDef *hadc;        // який АЦП (&hadc1)
    uint8_t            oversample;  // скільки вимірювань усереднювати (8)
    uint16_t           vref_mv;     // опорна напруга, мВ (3300)
} AdcIn_t;

void     AdcIn_Init  (AdcIn_t *a, ADC_HandleTypeDef *hadc, uint8_t oversample, uint16_t vref_mv);
uint16_t AdcIn_ReadMv(AdcIn_t *a);  // повертає напругу в мілівольтах

#endif /* DRV_ADC_H */
