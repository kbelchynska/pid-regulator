/* ============================================================================
 * drv_button.h — КНОПКА З ПРОГРАМНИМ АНТИБРЯЗКОТОМ (debounce)
 * ============================================================================
 * НАВІЩО: механічні контакти при натисканні "брязкають" — 1–10 мс швидко
 *   замикаються і розмикаються. Без фільтра одне натискання зарахувалося б
 *   кілька разів.
 *
 * ЯК ПРАЦЮЄ: нове значення приймається лише тоді, коли воно трималося
 *   N відліків поспіль (3 × 10 мс = 30 мс). Функція повертає true ОДИН раз —
 *   у момент натискання.
 *
 * ПРИКЛАД (1 = натиснута, stable спочатку 0, threshold = 3):
 *   відлік: 1  2  3  4  5  6
 *   raw:    1  0  1  1  1  1
 *   count:  1  0  1  2  3→0 0      → на 5-му відліку повертає true
 * ========================================================================== */
#ifndef DRV_BUTTON_H
#define DRV_BUTTON_H

#include "bsp_gpio.h"
#include <stdint.h>

typedef struct {
    DigitalIn_t in;          // пін кнопки
    uint8_t     threshold;   // скільки однакових відліків поспіль потрібно (3)
    uint8_t     count;       // скільки відліків поспіль стан відрізняється від стабільного
    bool        stable;      // підтверджений стан: true = натиснута
} Button_t;

void Button_Init(Button_t *b, DigitalIn_t in, uint8_t threshold);

/* Викликати періодично. Повертає true ОДИН раз — у момент натискання. */
bool Button_PollPressed(Button_t *b);

#endif /* DRV_BUTTON_H */
