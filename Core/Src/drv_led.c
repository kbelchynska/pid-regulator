/* ============================================================================
 * drv_led.c — драйвер світлодіода
 * ========================================================================== */
#include "drv_led.h"

void Led_Init(Led_t *led, DigitalOut_t out)
{
    led->out = out;               // скопіювати опис піна в об'єкт (об'єкт самодостатній)
    led->on  = false;             // на старті вимкнений
    DigitalOut_Init(&led->out);   // налаштувати пін (одразу у вимкненому стані)
}

void Led_Set(Led_t *led, bool on)
{
    led->on = on;                 // запам'ятати новий стан
    DigitalOut_Set(&led->out, on);// фізично встановити пін
}

void Led_Toggle(Led_t *led)
{
    Led_Set(led, !led->on);       // увімкнути, якщо був вимкнений, і навпаки.
}                                 // Для цього й потрібне поле on: читати вихідний пін назад ненадійно
