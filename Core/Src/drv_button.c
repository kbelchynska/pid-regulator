/* ============================================================================
 * drv_button.c — антибрязкіт лічильником відліків
 * ========================================================================== */
#include "drv_button.h"

void Button_Init(Button_t *b, DigitalIn_t in, uint8_t threshold)
{
    b->in        = in;
    b->threshold = threshold ? threshold : 1;   // якщо передали 0 — беремо 1
    b->count     = 0;
    DigitalIn_Init(&b->in);                     // налаштувати пін як вхід з підтяжкою
    b->stable    = DigitalIn_IsActive(&b->in);  // стартовий стан — з піна (щоб кнопка, затиснута
}                                               // при старті, не дала хибного "натискання")

bool Button_PollPressed(Button_t *b)
{
    bool raw = DigitalIn_IsActive(&b->in);      // "сирий" стан піна зараз

    if (raw == b->stable) {                     // нічого не змінилось →
        b->count = 0;                           // скинути лічильник (одиничний "стрибок" брязкоту
        return false;                           // так і відфільтровується)
    }
    if (++b->count < b->threshold) {            // змінилось, але ще не підтверджено.
        return false;                           // ++count спершу збільшує, потім порівнює
    }
    b->count  = 0;                              // зміна трималась 3 відліки поспіль →
    b->stable = raw;                            // прийняти новий стабільний стан
    return raw;                                 // true лише якщо новий стан = "натиснута"
}                                               // (відпускання кнопки не рахується)
