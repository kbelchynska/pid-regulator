/* ============================================================================
 * drv_adc.c — одиночні перетворення з опитуванням
 * ============================================================================
 * АЦП використовує лише задача регулятора (єдиний власник), тому захист
 * м'ютексом не потрібен.
 * ========================================================================== */
#include "drv_adc.h"

void AdcIn_Init(AdcIn_t *a, ADC_HandleTypeDef *hadc, uint8_t oversample, uint16_t vref_mv)
{
    a->hadc       = hadc;
    a->oversample = oversample ? oversample : 1;   // захист від 0
    a->vref_mv    = vref_mv;
}

uint16_t AdcIn_ReadMv(AdcIn_t *a)
{
    uint32_t acc = 0, n = 0;         // acc — сума, n — кількість вдалих вимірювань.
                                     // uint32_t, бо 8 × 4095 = 32760 — на межі 16 біт
    for (uint8_t i = 0; i < a->oversample; i++) {    // 8 разів:
        HAL_ADC_Start(a->hadc);                      // запустити перетворення
        if (HAL_ADC_PollForConversion(a->hadc, 1) == HAL_OK) {   // чекати результат ≤ 1 мс
            acc += HAL_ADC_GetValue(a->hadc);        // додати число 0…4095
            n++;                                     // рахуємо лише вдалі
        }
    }
    if (n == 0) return 0;                            // захист від ділення на 0
    return (uint16_t)(((acc / n) * a->vref_mv) / 4095u);
    // ↑ середнє → мВ: код × 3300 / 4095.  Напр. 1862 × 3300 / 4095 ≈ 1500 мВ.
    //   Спершу МНОЖИМО, потім ДІЛИМО — щоб не втратити точність у цілих числах
}
